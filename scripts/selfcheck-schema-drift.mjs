/**
 * Self-check: the Drizzle schema and the committed migrations agree.
 *
 * **Why this exists, measured 2026-10-25.** A peer session reviewing commit
 * 7f95717 changed `uniqueIndex("hotel_brand_rules_brand_key")` from
 * `.on(sql\`lower(${t.brand})\`)` to `.on(t.brand)` — a case-sensitive index,
 * the exact regression `selfcheck-config-schema`'s "a hotel brand holds one
 * stance whatever its capitalisation" is named for — and that check stayed
 * GREEN at 13 of 13. It asserts against the already-generated migration SQL,
 * so editing the schema source cannot fail it. Every structural assertion in
 * that file has the same shape, and so does `selfcheck-route-watch`.
 *
 * That is one assertion per claim, and a claim nobody wrote an assertion for
 * is unguarded. This is the assertion that covers all of them at once: if the
 * schema says something the committed migrations do not, `drizzle-kit
 * generate` has a new migration to emit, and that is a failure.
 *
 * It writes NOTHING into `drizzle-pg/`. The existing migrations and their
 * snapshots are copied into a temporary directory, a temporary config points
 * `out` at that copy, and both are deleted afterwards — so a drift that would
 * produce a migration file produces it somewhere disposable instead of
 * quietly appearing in the repo.
 *
 * Offline: `generate` reads the schema and the snapshot and never connects.
 * If drizzle-kit cannot run at all this FAILS rather than skipping, because a
 * check that skips what it cannot find is the instrument that cannot fail.
 */
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = join(root, "drizzle-pg");

const before = readdirSync(source)
  .filter((f) => f.endsWith(".sql"))
  .sort();
assert.ok(before.length > 0, "drizzle-pg holds no migrations, so there is nothing to compare");

/**
 * drizzle-kit resolves `out` RELATIVE TO CWD and prefixes it with "./", so an
 * absolute path becomes ".//var/folders/..." and it cannot find the snapshots
 * it just copied. The scratch directory therefore lives inside the repo, under
 * `node_modules/.cache` so git can never see it, and is passed as a relative
 * path.
 *
 * `node_modules/.cache` is created incidentally by a build tool, not by
 * `pnpm install`, so a fresh clone or a new worktree that runs
 * `pnpm run selfcheck` before a build — the normal order in CI — has no such
 * directory. Without the mkdir this died with `ENOENT ... mkdtemp`, which is a
 * crash rather than a verdict: a reader would see a broken check instead of
 * "no drift". Measured by a peer session 2026-10-25, and masked here because
 * this worktree had already run a build.
 */
const cacheRoot = join(root, "node_modules", ".cache");
mkdirSync(cacheRoot, { recursive: true });
const scratch = mkdtempSync(join(cacheRoot, "cs-drift-"));
const scratchRelative = relative(root, scratch);
// The config must sit in the repo root so its relative schema path resolves.
const configPath = join(root, `drizzle.drift-check.${process.pid}.config.ts`);

try {
  cpSync(source, scratch, { recursive: true });
  writeFileSync(
    configPath,
    [
      "// Generated by scripts/selfcheck-schema-drift.mjs. Deleted when it finishes.",
      'import { defineConfig } from "drizzle-kit";',
      "export default defineConfig({",
      '  dialect: "postgresql",',
      '  schema: "./src/backend/pg/schema.ts",',
      `  out: ${JSON.stringify(scratchRelative)},`,
      '  migrations: { table: "__drizzle_migrations", schema: "drizzle" },',
      "});",
      "",
    ].join("\n"),
  );

  const run = spawnSync(
    "pnpm",
    ["exec", "drizzle-kit", "generate", "--config", configPath, "--name", "drift_check"],
    { cwd: root, encoding: "utf8" },
  );

  const output = `${run.stdout ?? ""}${run.stderr ?? ""}`;
  // Measured 2026-10-25: drizzle-kit exits 0 even when it fails internally
  // (an ENOENT reading its own snapshots exited 0), so the exit status alone
  // would let a broken check read as a clean one. The output assertion below
  // is what actually proves the comparison happened.
  assert.equal(
    run.status,
    0,
    `drizzle-kit generate could not run, so schema drift is UNCHECKED rather than absent:\n${output}`,
  );

  const after = readdirSync(scratch)
    .filter((f) => f.endsWith(".sql"))
    .sort();
  const added = after.filter((f) => !before.includes(f));

  assert.deepEqual(
    added,
    [],
    [
      "The Drizzle schema and the committed migrations disagree.",
      `drizzle-kit would emit: ${added.join(", ")}`,
      "",
      "Run `pnpm run db:generate:pg` and `pnpm run migrate:pg`, then commit both the",
      "SQL and the snapshot. A committed schema with no matching migration deploys",
      "clean and fails at runtime, and /api/health compares the newest bundled",
      "migration against the database ledger.",
    ].join("\n"),
  );

  assert.match(
    output,
    /No schema changes, nothing to migrate/,
    `drizzle-kit emitted no new file but did not report a clean comparison:\n${output}`,
  );

  console.log(
    `selfcheck-schema-drift: ok (${before.length} migrations, schema matches, nothing to emit)`,
  );
} finally {
  rmSync(scratch, { recursive: true, force: true });
  rmSync(configPath, { force: true });
}

// The repo's own migration directory must be untouched by this check.
const untouched = readdirSync(source)
  .filter((f) => f.endsWith(".sql"))
  .sort();
assert.deepEqual(untouched, before, "the drift check wrote into drizzle-pg; it must not");
